#!/usr/bin/env python3
# SPDX-License-Identifier: BSD-2-Clause
"""M0 ABI test: do the V4L2 and media ioctls we would implement carry the same
(direction, group, number, argument size) on FreeBSD as in the Linux UAPI?

The Linux UAPI headers are the reference. They are read from a Linux source
tree (default /opt/bzdos/linux-work/linux-6.12), not copied here, because
media.h, v4l2-subdev.h, v4l2-mediabus.h and media-bus-format.h are GPL-only.

  1. Extract every VIDIOC_*/MEDIA_* ioctl name from the reference headers.
  2. Evaluate each one with the Linux headers, twice: natively, and as an
     aarch64 object whose .rodata is read back. Both must agree.
  3. Emit abi_expect.h and compile it against the FreeBSD sysroot with the
     UAPI headers and the shims in shim/. Any mismatch is a _Static_assert.

usage: gen_abi.py [--linux DIR] [--sysroot DIR] [--keep]
"""
import argparse, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
UAPI = os.path.join(HERE, '..', '..', 'uapi')
HEADERS = ['videodev2.h', 'media.h', 'v4l2-subdev.h']
BSD_DIR = {0: 'IOC_VOID', 1: 'IOC_IN', 2: 'IOC_OUT', 3: 'IOC_INOUT'}  # Linux dir -> FreeBSD


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit('FAILED: %s\n%s%s' % (' '.join(cmd), r.stdout, r.stderr))
    return r.stdout


def ioctl_names(linux):
    names = []
    for h in HEADERS:
        text = open(os.path.join(linux, 'include/uapi/linux', h)).read()
        text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        for m in re.finditer(r'^#define\s+((?:VIDIOC|MEDIA)_\w+)\s*\\?\s*(_IO[RW]*)\s*\(', text, re.M):
            names.append(m.group(1))
    return names


def dump_source(names):
    s = ['#include <linux/videodev2.h>', '#include <linux/media.h>', '#include <linux/v4l2-subdev.h>',
         '#ifndef OBJ_ONLY', '#include <stdio.h>', '#endif',
         'struct ent { unsigned dir, type, nr, size; };',
         'const struct ent abi_tab[] = {']
    for n in names:
        s.append('\t{ _IOC_DIR(%s), _IOC_TYPE(%s), _IOC_NR(%s), _IOC_SIZE(%s) },' % (n, n, n, n))
    s += ['};', 'const unsigned abi_n = %d;' % len(names),
          '#ifndef OBJ_ONLY',
          'int main(void) { for (unsigned i = 0; i < abi_n; i++)',
          '  printf("%u %u %u %u\\n", abi_tab[i].dir, abi_tab[i].type, abi_tab[i].nr, abi_tab[i].size);',
          '  return 0; }', '#endif']
    return '\n'.join(s) + '\n'


def parse_rodata(objdump_out, count):
    """aarch64 little-endian .rodata dump -> list of (dir,type,nr,size)."""
    data = b''
    for line in objdump_out.splitlines():
        m = re.match(r'^\s+[0-9a-f]+\s+((?:[0-9a-f]{2,8}\s?){1,4})', line)
        if m:
            data += bytes.fromhex(m.group(1).replace(' ', ''))
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data) - 3, 4)]
    return [tuple(words[i * 4:i * 4 + 4]) for i in range(count)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--linux', default='/opt/bzdos/linux-work/linux-6.12')
    ap.add_argument('--sysroot', default='/opt/bzdos/sysroots/aarch64-15.1')
    ap.add_argument('--keep', action='store_true')
    a = ap.parse_args()

    names = ioctl_names(a.linux)
    if len(names) < 100:
        sys.exit('only %d ioctl names found; the extraction regex is broken' % len(names))
    print('%d ioctls in %s' % (len(names), ', '.join(HEADERS)))

    tmp = tempfile.mkdtemp(prefix='media-abi.')
    src = os.path.join(tmp, 'linux_dump.c')
    open(src, 'w').write(dump_source(names))
    inc = ['-I' + os.path.join(HERE, 'linux-asm-shim'), '-I' + os.path.join(a.linux, 'include/uapi')]

    # native (x86_64 host, LP64)
    exe = os.path.join(tmp, 'linux_dump')
    run(['gcc', '-std=gnu11', '-w'] + inc + ['-o', exe, src])
    native = [tuple(map(int, l.split())) for l in run([exe]).splitlines()]

    # aarch64 object, read back from .rodata
    obj = os.path.join(tmp, 'linux_dump_a64.o')
    run(['aarch64-linux-gnu-gcc', '-std=gnu11', '-w', '-DOBJ_ONLY', '-c',
         '-I' + os.path.join(HERE, 'linux-a64-shim')] + inc + ['-o', obj, src])
    a64 = parse_rodata(run(['aarch64-linux-gnu-objdump', '-s', '-j', '.rodata', obj]), len(names))
    if native != a64:
        bad = [(n, x, y) for n, x, y in zip(names, native, a64) if x != y]
        sys.exit('x86_64 and aarch64 Linux tables disagree (%d): %s' % (len(bad), bad[:5]))
    print('Linux table: x86_64 and aarch64 agree')
    table = a64

    over = [n for n, e in zip(names, table) if e[3] > 8191]
    if over:
        sys.exit('argument size does not fit FreeBSD IOCPARM (8191): %s' % over)

    exp = os.path.join(tmp, 'abi_expect.h')
    with open(exp, 'w') as f:
        f.write('/* generated by gen_abi.py from the Linux UAPI headers */\n')
        f.write('#define ABI(n, dir, grp, nr, sz) \\\n'
                '  _Static_assert(IOCPARM_LEN(n) == (sz), #n ": argument size"); \\\n'
                '  _Static_assert(IOCGROUP(n) == (grp), #n ": group"); \\\n'
                '  _Static_assert(((n) & 0xff) == (nr), #n ": number"); \\\n'
                '  _Static_assert(((n) & IOC_DIRMASK) == (dir), #n ": direction");\n')
        for n, (d, t, nr, sz) in zip(names, table):
            f.write('ABI(%s, %s, %d, %d, %d)\n' % (n, BSD_DIR[d], t, nr, sz))

    chk = os.path.join(tmp, 'check.c')
    open(chk, 'w').write('#include <sys/types.h>\n#include <sys/time.h>\n#include <sys/ioccom.h>\n'
                         '#include <linux/videodev2.h>\n#include <linux/media.h>\n'
                         '#include <linux/v4l2-subdev.h>\n#include "abi_expect.h"\n')
    bsd = ['clang', '--target=aarch64-unknown-freebsd15.1', '--sysroot=' + a.sysroot,
           '-fsyntax-only', '-Wall', '-Werror',
           '-I' + os.path.join(HERE, 'shim'), '-I' + os.path.join(a.linux, 'include/uapi'),
           '-I' + tmp]
    # The dual-licensed headers must come from the tree we ship, not from Linux.
    bsd = [x for x in bsd if not x.startswith('-I' + os.path.join(a.linux))]
    bsd += ['-I' + UAPI, '-I' + os.path.join(a.linux, 'include/uapi')]
    r = subprocess.run(bsd + [chk], capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stderr)
        sys.exit('FreeBSD side does not match (%d errors)' % r.stderr.count('error:'))
    print('FreeBSD: %d ioctls match (direction, group, number, size)' % len(names))
    print('OK')
    if a.keep:
        print('kept', tmp)


if __name__ == '__main__':
    main()
